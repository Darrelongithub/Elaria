#!/usr/bin/env python3
"""Frame-level packet: where do full-scale samples live in a wav?

Owner-runnable (2026-11-15). One physical line, numbers only, no network, no
credentials, stdlib only:

    python3 scripts/frame_probe.py /path/to/file.wav

Why it exists: the mute test reported rms 0.007 with the node muted but peak
0.9981 — speech gone, a full-scale sample surviving mute. A sample that
survives the node's volume is not room sound; it is a transient injected at or
after stream open (start-pop / DSP power-up click). Diagnoses anchored on the
full-file PEAK therefore cannot tell a pop from a hot voice — and neither can a
single number. This packet prints the per-50 ms-frame peak and RMS and says
where the full-scale samples are:

    D-A  the full-scale samples sit in the first frames (a start pop);
    D-B  they are spread through the take (the voice itself is at full scale).

Read the SUMMARY block: `verdict`, `first_full_scale_ms`, `last_full_scale_ms`,
`full_scale_after_start` and `recommended_start_pop_ms`. Everything after
`FRAME` lines is the raw table, one row per frame, for anyone who wants to see
it rather than trust it.

Integrity: `scripts/frame_probe.py.sha256` holds this file's digest under its
REPOSITORY-RELATIVE name, so `sha256sum -c scripts/frame_probe.py.sha256`
verifies from the repository root exactly as every other pin in this house does
(a bare filename would only verify from inside `scripts/`). The manifest is
regenerated by `python3 scripts/frame_probe.py --checksum` and pinned by
`tests/test_frame_probe.py`.
"""

from __future__ import annotations

import hashlib
import math
import struct
import sys
import wave
from pathlib import Path

FRAME_MS = 50
#: A sample at or above this fraction of full scale is called full-scale. 0.99
#: rather than 1.0: a limiter or a resampler can leave 32767 or 32766 either
#: side of the boundary, and the diagnosis is about the shape, not the digit.
FULL_SCALE = 0.99
#: How long after stream open a transient may still be called a "start" event.
#: Two frames: a power-up click is milliseconds, and anything later than this
#: is either the person or a genuinely broken stream.
START_WINDOW_MS = 2 * FRAME_MS


def _frames(pcm: bytes, sample_rate: int, frame_ms: int) -> list[dict]:
    """Decode s16le mono into per-frame peak/rms rows."""
    samples = struct.unpack(f"<{len(pcm) // 2}h",
                            pcm[: len(pcm) - len(pcm) % 2])
    per_frame = max(1, int(sample_rate * frame_ms / 1000))
    rows: list[dict] = []
    for index, start in enumerate(range(0, len(samples), per_frame)):
        chunk = samples[start:start + per_frame]
        if not chunk:
            continue
        peak = max(abs(value) for value in chunk) / 32768
        rms = math.sqrt(sum(value * value for value in chunk) / len(chunk)) / 32768
        rows.append({"index": index, "start_ms": index * frame_ms,
                     "peak": peak, "rms": rms})
    return rows


def analyse(path: Path, *, frame_ms: int = FRAME_MS) -> dict:
    """The whole analysis as numbers. No printing, so tests can pin it."""
    with wave.open(str(path), "rb") as wav:
        channels = wav.getnchannels()
        width = wav.getsampwidth()
        sample_rate = wav.getframerate()
        raw = wav.readframes(wav.getnframes())
    if width != 2:
        raise ValueError(f"need 16-bit PCM (s16le); this file is {8 * width}-bit")
    if channels > 1:
        # Downmix to mono so peak/rms mean the same thing on every take.
        samples = struct.unpack(f"<{len(raw) // 2}h", raw[: len(raw) - len(raw) % 2])
        mono = [sum(samples[i:i + channels]) // channels
                for i in range(0, len(samples) - channels + 1, channels)]
        raw = struct.pack(f"<{len(mono)}h", *mono)
    rows = _frames(raw, sample_rate, frame_ms)
    duration_ms = len(raw) // 2 / sample_rate * 1000
    full = [row for row in rows if row["peak"] >= FULL_SCALE]
    after_start = [row for row in full if row["start_ms"] >= START_WINDOW_MS]
    steady_rows = [row for row in rows if row["start_ms"] >= START_WINDOW_MS]

    last_full = full[-1]["start_ms"] if full else None
    first_full = full[0]["start_ms"] if full else None
    if not full:
        verdict = "clean"
    elif not after_start:
        verdict = "pop_at_start"
    elif first_full is not None and first_full < START_WINDOW_MS:
        verdict = "mixed"
    else:
        verdict = "steady_clip"

    # The recommendation is the end of the leading full-scale run, rounded up
    # to a frame and capped at the start window: the hold-off only has to cover
    # the transient, never the person.
    if verdict in ("pop_at_start", "mixed"):
        recommended = min(START_WINDOW_MS,
                          int(math.ceil((last_full + frame_ms) / frame_ms) * frame_ms))
    else:
        recommended = 0

    return {
        "file": path.name,
        "sample_rate": sample_rate,
        "channels": channels,
        "frame_ms": frame_ms,
        "duration_ms": round(duration_ms, 1),
        "frames": len(rows),
        "peak_full": round(max((row["peak"] for row in rows), default=0.0), 4),
        "peak_steady": round(max((row["peak"] for row in steady_rows), default=0.0), 4),
        "rms_full": round(frame_rms_of(rows), 4),
        "rms_steady": round(frame_rms_of(steady_rows), 4),
        "full_scale_frames": len(full),
        "full_scale_after_start": len(after_start),
        "first_full_scale_ms": first_full,
        "last_full_scale_ms": last_full,
        "start_window_ms": START_WINDOW_MS,
        "recommended_start_pop_ms": recommended,
        "verdict": verdict,
        "rows": rows,
    }


def frame_rms_of(rows: list[dict]) -> float:
    """Energy of a span: RMS of the per-frame RMS values (a rate, not a sum)."""
    if not rows:
        return 0.0
    return math.sqrt(sum(row["rms"] ** 2 for row in rows) / len(rows))


def _num(value) -> str:
    """Numbers only: a missing reading is -1, never the word `None`."""
    return "-1" if value is None else str(value)


def render(result: dict) -> str:
    """Numbers only, `key value` then the frame table."""
    lines = [f"file {result['file']}",
             f"sample_rate {result['sample_rate']}",
             f"channels {result['channels']}",
             f"frame_ms {result['frame_ms']}",
             f"duration_ms {result['duration_ms']}",
             f"frames {result['frames']}",
             f"peak_full {result['peak_full']:.4f}",
             f"peak_steady {result['peak_steady']:.4f}",
             f"rms_full {result['rms_full']:.4f}",
             f"rms_steady {result['rms_steady']:.4f}",
             f"full_scale_frames {result['full_scale_frames']}",
             f"full_scale_after_start {result['full_scale_after_start']}",
             f"first_full_scale_ms {_num(result['first_full_scale_ms'])}",
             f"last_full_scale_ms {_num(result['last_full_scale_ms'])}",
             f"start_window_ms {result['start_window_ms']}",
             f"recommended_start_pop_ms {result['recommended_start_pop_ms']}",
             f"verdict {result['verdict']}",
             "FRAME index start_ms peak rms"]
    for row in result["rows"]:
        lines.append(f"FRAME {row['index']} {row['start_ms']} "
                     f"{row['peak']:.4f} {row['rms']:.4f}")
    return "\n".join(lines)


def checksum() -> str:
    """The digest of this file, for the manifest beside it."""
    return hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def manifest_name() -> str:
    """This file's path relative to the repository root (`scripts/…`)."""
    here = Path(__file__).resolve()
    return f"{here.parent.name}/{here.name}"


def write_manifest(target: Path | None = None) -> Path:
    path = target or Path(__file__).with_suffix(".py.sha256")
    path.write_text(f"{checksum()}  {manifest_name()}\n")
    return path


def main(argv: list[str]) -> int:
    if not argv or argv[0] in ("-h", "--help"):
        print("usage: frame_probe.py <file.wav> | --checksum", file=sys.stderr)
        return 2
    if argv[0] == "--checksum":
        print(write_manifest())
        return 0
    path = Path(argv[0]).expanduser()
    if not path.exists():
        print(f"error missing_file {path}", file=sys.stderr)
        return 2
    try:
        result = analyse(path)
    except (wave.Error, ValueError) as exc:
        print(f"error unreadable {exc}", file=sys.stderr)
        return 2
    print(render(result))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
